#!/usr/bin/env bash
set -euo pipefail

echo ">>> [DA-RESET] Arrêt de Turbo dev (si encore actif)..."
pkill -f "turbo run dev" >/dev/null 2>&1 || true

echo ">>> [DA-RESET] Nettoyage des caches Metro / Expo..."
rm -rf .expo
find apps -maxdepth 2 -type d \( -name ".expo" -o -name ".expo-shared" \) -print -exec rm -rf {} +
rm -rf node_modules/.cache

echo ">>> [DA-RESET] Suppression des node_modules du monorepo et des apps..."
rm -rf node_modules

for dir in apps/client apps/courier apps/merchant; do
  if [ -d "$dir/node_modules" ]; then
    echo "    - remove $dir/node_modules"
    rm -rf "$dir/node_modules"
  fi
done

echo ">>> [DA-RESET] Réinstallation des dépendances (pnpm install)..."
pnpm install

echo ">>> [DA-RESET] Terminé. Tu peux relancer : pnpm dev -- --clear"
